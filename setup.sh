#!/usr/bin/env bash

# Setup script for Obsidian to Grafana monitoring
# Creates a virtualenv, starts the Docker stack and installs cron jobs that run
# the parser and the vault index every 5 minutes. Safe to re-run.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOG_DIR="$SCRIPT_DIR/logs"
VENV_DIR="$SCRIPT_DIR/.venv"
VENV_PYTHON="$VENV_DIR/bin/python"
CONFIG_FILE="$SCRIPT_DIR/config.yaml"
CRON_MARKER="# obsidian-grafana"

echo "🚀 Setting up Obsidian to Grafana monitoring system..."

fail() {
    echo "❌ Error: $1" >&2
    exit 1
}

# --- Dependency checks -------------------------------------------------------
command -v python3 >/dev/null 2>&1 || fail "python3 is required but was not found."
command -v docker >/dev/null 2>&1 || fail "docker is required but was not found."
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 ('docker compose') is required. The old 'docker-compose' v1 binary is not supported."
docker info >/dev/null 2>&1 || fail "the Docker daemon is not running (or not reachable by this user)."
command -v crontab >/dev/null 2>&1 || fail "crontab is required but was not found."

# --- Config ------------------------------------------------------------------
if [ ! -f "$CONFIG_FILE" ]; then
    echo "❌ Error: config.yaml not found!" >&2
    echo "Copy config.yaml.example to config.yaml and set vault_path and grafana_password." >&2
    exit 1
fi

# --- Python environment (used here to read config, and by cron) --------------
if [ ! -x "$VENV_PYTHON" ]; then
    echo "🐍 Creating virtualenv in $VENV_DIR..."
    python3 -m venv "$VENV_DIR" || fail "could not create a virtualenv (on Debian/Ubuntu: apt install python3-venv)."
fi
echo "📦 Installing Python dependencies..."
"$VENV_PYTHON" -m pip install --quiet --disable-pip-version-check -r "$SCRIPT_DIR/requirements.txt"

# Extract configuration from config.yaml (single source of truth for these values)
read_config() {
    "$VENV_PYTHON" - "$CONFIG_FILE" "$1" <<'PY'
import sys, yaml
with open(sys.argv[1]) as f:
    value = (yaml.safe_load(f) or {}).get(sys.argv[2])
print("" if value is None else value)
PY
}

echo "📋 Reading configuration from config.yaml..."
GRAFANA_PASSWORD="$(read_config grafana_password)"
VAULT_PATH="$(read_config vault_path)"

if [ -z "$GRAFANA_PASSWORD" ] || [ "$GRAFANA_PASSWORD" = "your_grafana_password_here" ]; then
    fail "grafana_password in config.yaml is missing or still the placeholder. Set a password of your choice (there is no default)."
fi

if [ -z "$VAULT_PATH" ] || [ ! -d "$VAULT_PATH" ]; then
    fail "vault_path in config.yaml is missing or does not exist: $VAULT_PATH"
fi

# Export for docker compose
export GRAFANA_PASSWORD
export VAULT_PATH

# Keep plain `docker compose ...` commands working (down, logs, ps): compose needs the same
# two values, so mirror them into .env. An .env you wrote yourself is never overwritten.
ENV_FILE="$SCRIPT_DIR/.env"
ENV_HEADER="# Generated by setup.sh from config.yaml - edit config.yaml, not this file."
if [ ! -f "$ENV_FILE" ] || head -n 1 "$ENV_FILE" | grep -qF -- "$ENV_HEADER"; then
    case "$VAULT_PATH$GRAFANA_PASSWORD" in
        *"'"*)
            echo "ℹ️  Not writing .env (a value contains a single quote). Plain 'docker compose' commands need VAULT_PATH and GRAFANA_PASSWORD exported." ;;
        *)
            ( umask 077
              printf '%s\nVAULT_PATH='"'%s'"'\nGRAFANA_PASSWORD='"'%s'"'\n' "$ENV_HEADER" "$VAULT_PATH" "$GRAFANA_PASSWORD" > "$ENV_FILE" ) ;;
    esac
else
    echo "ℹ️  Keeping your existing .env (setup.sh passes the config.yaml values directly, so setup is unaffected)."
fi

# Create the logs directory before Docker does (otherwise Docker creates it owned by root)
mkdir -p "$LOG_DIR"

# Start the Docker stack
echo "🐳 Starting Docker containers..."
cd "$SCRIPT_DIR"
docker compose up -d --build

# --- Cron --------------------------------------------------------------------
echo "⏰ Setting up cron jobs for Obsidian parser and vault index..."

PARSER_CRON="*/5 * * * * $SCRIPT_DIR/scripts/cron-parse.sh $CRON_MARKER:parser"
INDEX_CRON="*/5 * * * * $SCRIPT_DIR/scripts/cron-index.sh $CRON_MARKER:index"

# Drop entries from earlier runs of this script (current marker, or the legacy
# format that called the Python files directly) so re-running never duplicates jobs.
EXISTING_CRON="$(crontab -l 2>/dev/null || true)"
KEPT_CRON="$(printf '%s\n' "$EXISTING_CRON" | grep -v -F -e "$CRON_MARKER" -e "$SCRIPT_DIR/parse_notes.py" -e "$SCRIPT_DIR/export_vault_index.py" -e "$SCRIPT_DIR/scripts/cron-" || true)"
if [ "$KEPT_CRON" != "$EXISTING_CRON" ]; then
    echo "   (replacing previously installed obsidian-grafana cron entries)"
fi
{
    [ -n "$KEPT_CRON" ] && printf '%s\n' "$KEPT_CRON"
    printf '%s\n%s\n' "$PARSER_CRON" "$INDEX_CRON"
} | crontab -

echo ""
echo "✅ Setup complete!"
echo ""
echo "🌐 Access your services (bound to localhost only):"
echo "   • Grafana: http://localhost:3000 (user: admin, password: grafana_password from config.yaml)"
echo "   • Prometheus: http://localhost:9090"
echo "   • Loki: http://localhost:3100"
echo "   • Metrics Exporter: http://localhost:8080"
echo ""
echo "📊 The parser and vault index will run every 5 minutes automatically"
echo "📝 Parser logs: $LOG_DIR/obsidian_parser.log"
echo "📝 Index logs: $LOG_DIR/vault_index.log"
echo ""
echo "🔧 Management commands:"
echo "   • View logs: docker compose logs -f"
echo "   • Stop system: docker compose down"
echo "   • View cron jobs: crontab -l"
echo "   • Remove cron jobs: crontab -e (delete the lines ending in '$CRON_MARKER:parser' / '$CRON_MARKER:index')"
